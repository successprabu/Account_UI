import { useCallback, useEffect, useMemo, useState } from 'react';
import { useTranslation } from 'react-i18next';
import { AnimatePresence, motion } from 'framer-motion';
import { toast } from 'react-toastify';
import {
  Alert,
  Box,
  Button,
  Card,
  CircularProgress,
  Grid,
  MenuItem,
  Pagination,
  Skeleton,
  Stack,
  Table,
  TableBody,
  TableCell,
  TableContainer,
  TableHead,
  TableRow,
  TextField,
  Typography,
  useMediaQuery,
} from '@mui/material';
import { alpha, useTheme } from '@mui/material/styles';
import SearchIcon from '@mui/icons-material/Search';
import ClearIcon from '@mui/icons-material/Clear';
import PictureAsPdfOutlinedIcon from '@mui/icons-material/PictureAsPdfOutlined';
import GridOnOutlinedIcon from '@mui/icons-material/GridOnOutlined';
import AssessmentOutlinedIcon from '@mui/icons-material/AssessmentOutlined';
import { API_SERVICE } from '../common/CommonMethod';
import { REPORT_GET_GENERALDATA_API } from '../common/CommonApiURL';
import { EmptyState, PageHeader } from '../ui';
import { AnimatedNumber, EntryField, useVoice } from './shared';
import { downloadReportPdf, exportExcel } from './reportExport';

export const readUser = () => {
  try {
    return JSON.parse(localStorage.getItem('user'));
  } catch (e) {
    return null;
  }
};

const PAGE_SIZES = [10, 25, 50, 100];

/** Function details, report date and footer text for the PDF (same call the reports always used). */
export const pdfInfo = async (t) => {
  const user = readUser();
  let data = {};
  try {
    const res = await API_SERVICE.get(REPORT_GET_GENERALDATA_API, {
      customer_id: user?.customerID,
      function_id: user?.functionId || 0,
      user_type: user?.userType || '',
      userId: user?.id || 0,
    });
    data = res?.data?.data || {};
  } catch (e) {
    console.error('Report details could not be loaded', e);
  }
  const fn = data.functions || {};
  return {
    functionName: fn.functionName,
    functionDate: fn.functionDate,
    persons: fn.funPersionNames,
    place: fn.mahalName,
    reportDate: data.header?.reportDate || new Date().toISOString(),
    generatedBy: data.header?.generatedBy || user?.name || '',
    poweredBy: data.footer?.poweredBy || 'MySuccess.com',
    supportPhone: data.footer?.supportPhone || '+918050386769',
    functionNameLabel: t('functionName'),
    functionDateLabel: t('functionDate'),
    personsLabel: t('funPersionNames'),
    placeLabel: t('mahalName'),
    reportDateLabel: t('reportDate', { defaultValue: 'Report date' }),
    generatedByLabel: t('generatedBy', { defaultValue: 'Generated by' }),
    poweredByLabel: t('poweredBy', { defaultValue: 'Powered by' }),
    supportLabel: t('support', { defaultValue: 'Support' }),
    pageLabel: t('page', { defaultValue: 'Page' }),
  };
};

/** Buttons shared by every report. */
export const ExportButtons = ({ onExcel, onPdf, disabled }) => {
  const { t } = useTranslation();
  const [busy, setBusy] = useState('');
  const run = (kind, fn) => async () => {
    setBusy(kind);
    try {
      await fn();
    } catch (e) {
      console.error(`${kind} export failed`, e);
      toast.error(t('exportFailed', { defaultValue: 'Could not create the file. Please try again.' }));
    } finally {
      setBusy('');
    }
  };
  return (
    <>
      <Button variant="outlined" color="success" startIcon={busy === 'excel' ? <CircularProgress size={16} /> : <GridOnOutlinedIcon />} onClick={run('excel', onExcel)} disabled={disabled || !!busy}>
        Excel
      </Button>
      <Button variant="contained" color="error" startIcon={busy === 'pdf' ? <CircularProgress size={16} color="inherit" /> : <PictureAsPdfOutlinedIcon />} onClick={run('pdf', onPdf)} disabled={disabled || !!busy}>
        {busy === 'pdf' ? t('preparing', { defaultValue: 'Preparing…' }) : 'PDF'}
      </Button>
    </>
  );
};

/**
 * A report over all entries of the current function.
 *
 * load(filters) → Promise<rows>; filters: [{ key, label, digits }]
 * columns: [{ key, label, align, render(row) for the screen, value(row) for Excel/PDF }]; key "sNo" numbers rows
 * totalKeys: columns that get a total; stats(rows, totals) → [{ label, value, money, color }]
 * renderCard(row, index): phone layout
 */
const ReportPage = ({ title, subtitle, pdfTitle, fileBase, columns, totalKeys = [], filters = [], load, stats, renderCard, extraActions }) => {
  const { t, i18n } = useTranslation();
  const theme = useTheme();
  const wide = useMediaQuery(theme.breakpoints.up('md'));
  const voice = useVoice(i18n.language);
  const emptyFilters = useMemo(() => Object.fromEntries(filters.map((f) => [f.key, ''])), [filters]);
  const [values, setValues] = useState(emptyFilters);
  const [applied, setApplied] = useState(emptyFilters);
  const [rows, setRows] = useState([]);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState('');
  const [page, setPage] = useState(1);
  const [pageSize, setPageSize] = useState(25);

  const fetchRows = useCallback(async () => {
    setLoading(true);
    setError('');
    try {
      setRows((await load(applied)) || []);
    } catch (e) {
      console.error('Report could not be loaded', e);
      setError(t('loadFailed', { defaultValue: 'Could not load the report. Check your connection and try again.' }));
      setRows([]);
    } finally {
      setLoading(false);
    }
  }, [applied, load, t]);

  useEffect(() => {
    fetchRows();
  }, [fetchRows]);

  const totals = useMemo(
    () => Object.fromEntries(totalKeys.map((k) => [k, rows.reduce((a, r) => a + (Number(r[k]) || 0), 0)])),
    [rows, totalKeys]
  );
  const pages = Math.max(1, Math.ceil(rows.length / pageSize));
  const visible = rows.slice((page - 1) * pageSize, page * pageSize);
  const filtered = Object.values(applied).some(Boolean);
  const statList = stats ? stats(rows, totals) : [];

  const search = (e) => {
    e?.preventDefault();
    setPage(1);
    setApplied({ ...values });
  };
  const clear = () => {
    setValues(emptyFilters);
    setPage(1);
    setApplied(emptyFilters);
  };

  const exportCols = columns.map((c) => ({ ...c, value: c.value || ((r) => r[c.key]) }));
  const totalsRow = totalKeys.length ? { label: t('total'), values: Object.fromEntries(totalKeys.map((k) => [k, Math.round(totals[k] * 100) / 100])) } : null;
  const toExcel = () => exportExcel({ fileName: `${fileBase}.xlsx`, sheetName: pdfTitle, columns: exportCols, rows, totals: totalsRow });
  const toPdf = async () =>
    downloadReportPdf({
      fileName: `${fileBase}.pdf`,
      title: pdfTitle,
      columns: exportCols,
      rows,
      totals: totalsRow,
      info: await pdfInfo(t),
      summary: statList.map((s) => [s.label, s.money ? `₹${Number(s.value || 0).toLocaleString('en-IN')}` : s.value]),
    });

  return (
    <Box sx={{ py: { xs: 2.5, md: 3 } }}>
      <PageHeader
        title={title}
        subtitle={subtitle}
        breadcrumbs={[{ label: t('dashboard'), to: '/dashboard' }, { label: title }]}
        actions={
          <>
            {extraActions}
            <ExportButtons onExcel={toExcel} onPdf={toPdf} disabled={loading || rows.length === 0} />
          </>
        }
      />

      {statList.length > 0 && (
        <Grid container spacing={2} sx={{ mb: 2.5 }}>
          {statList.map((s, i) => (
            <Grid item xs={6} md={12 / Math.min(4, statList.length)} key={s.label}>
              <Card component={motion.div} initial={{ opacity: 0, y: 12 }} animate={{ opacity: 1, y: 0, transition: { delay: i * 0.06 } }} sx={{ p: 2, height: '100%', borderTop: `3px solid ${s.color || theme.palette.primary.main}` }}>
                <Typography variant="body2" color="text.secondary">{s.label}</Typography>
                {loading ? <Skeleton width="60%" height={36} /> : (
                  <Typography variant="h5" component="p" fontWeight={800} sx={{ mt: 0.5, fontVariantNumeric: 'tabular-nums' }}>
                    {s.money ? <AnimatedNumber value={s.value} /> : <AnimatedNumber value={s.value} format={(v) => Number(v).toLocaleString('en-IN')} />}
                  </Typography>
                )}
              </Card>
            </Grid>
          ))}
        </Grid>
      )}

      {filters.length > 0 && (
        <Card component="form" onSubmit={search} sx={{ p: { xs: 2, md: 2.5 }, mb: 2.5 }}>
          <Grid container spacing={1.5} alignItems="center">
            {filters.map((f) => (
              <Grid item xs={12} sm={6} md={filters.length > 2 ? 3 : 4} key={f.key}>
                <EntryField
                  size="small"
                  label={f.label}
                  value={values[f.key]}
                  type={f.digits ? 'tel' : 'text'}
                  onChange={(e) => setValues((v) => ({ ...v, [f.key]: e.target.value }))}
                  onKeyDown={(e) => e.key === 'Enter' && search(e)}
                  recording={voice.field === f.key}
                  onMic={() => voice.toggle(f.key, (said) => setValues((v) => ({ ...v, [f.key]: f.digits ? said.replace(/\D/g, '') : said })))}
                />
              </Grid>
            ))}
            <Grid item xs={12} md>
              <Stack direction="row" spacing={1}>
                <Button type="submit" variant="contained" startIcon={<SearchIcon />} sx={{ flex: 1 }}>{t('search')}</Button>
                <Button onClick={clear} startIcon={<ClearIcon />} disabled={!filtered && !Object.values(values).some(Boolean)}>{t('clearButton')}</Button>
              </Stack>
            </Grid>
          </Grid>
        </Card>
      )}

      {error && <Alert severity="error" sx={{ mb: 2 }} action={<Button color="inherit" onClick={fetchRows}>{t('retry', { defaultValue: 'Retry' })}</Button>}>{error}</Alert>}

      {loading && rows.length === 0 ? (
        <Stack spacing={1}>{[0, 1, 2, 3, 4].map((i) => <Skeleton key={i} variant="rounded" height={48} />)}</Stack>
      ) : rows.length === 0 && !error ? (
        <Card>
          <EmptyState
            icon={<AssessmentOutlinedIcon />}
            title={filtered ? t('noMatchesSearch', { defaultValue: 'Nothing matches your search' }) : t('noData')}
            description={filtered ? t('tryOtherSearch', { defaultValue: 'Try a different name, place or number.' }) : t('noReportData', { defaultValue: 'Entries for the current function appear here.' })}
            action={filtered ? <Button onClick={clear}>{t('clearButton')}</Button> : undefined}
          />
        </Card>
      ) : (
        <>
          <Stack direction="row" alignItems="center" justifyContent="space-between" sx={{ mb: 1.5 }}>
            <Typography variant="body2" color="text.secondary">
              {t('showingRows', { defaultValue: '{{from}}–{{to}} of {{total}}', from: (page - 1) * pageSize + 1, to: Math.min(page * pageSize, rows.length), total: rows.length })}
            </Typography>
            <TextField select size="small" label={t('pageSize')} value={pageSize} onChange={(e) => { setPageSize(Number(e.target.value)); setPage(1); }} sx={{ width: 110 }}>
              {PAGE_SIZES.map((n) => <MenuItem key={n} value={n}>{n}</MenuItem>)}
            </TextField>
          </Stack>
          {wide || !renderCard ? (
            <TableContainer component={Card} sx={{ opacity: loading ? 0.6 : 1 }}>
              <Table size="small">
                <TableHead>
                  <TableRow>{columns.map((c) => <TableCell key={c.key} align={c.align}>{c.label}</TableCell>)}</TableRow>
                </TableHead>
                <TableBody>
                  {visible.map((r, i) => (
                    <TableRow key={r.id ?? `${page}-${i}`} hover component={motion.tr} initial={{ opacity: 0 }} animate={{ opacity: 1, transition: { delay: Math.min(i, 15) * 0.015 } }}>
                      {columns.map((c) => (
                        <TableCell key={c.key} align={c.align} sx={c.bold ? { fontWeight: 700 } : undefined}>
                          {c.key === 'sNo' ? (page - 1) * pageSize + i + 1 : c.render ? c.render(r) : r[c.key]}
                        </TableCell>
                      ))}
                    </TableRow>
                  ))}
                  {totalKeys.length > 0 && page === pages && (
                    <TableRow sx={{ '& td': { fontWeight: 800, bgcolor: alpha(theme.palette.primary.main, 0.06) } }}>
                      {columns.map((c, i) => (
                        <TableCell key={c.key} align={c.align}>
                          {i === 0 ? t('total') : totalKeys.includes(c.key) ? (c.render ? c.render({ [c.key]: totals[c.key] }) : totals[c.key]) : ''}
                        </TableCell>
                      ))}
                    </TableRow>
                  )}
                </TableBody>
              </Table>
            </TableContainer>
          ) : (
            <Stack spacing={1.25} sx={{ opacity: loading ? 0.6 : 1 }}>
              <AnimatePresence initial={false}>
                {visible.map((r, i) => (
                  <Card key={r.id ?? `${page}-${i}`} component={motion.div} initial={{ opacity: 0, y: 8 }} animate={{ opacity: 1, y: 0, transition: { delay: Math.min(i, 10) * 0.03 } }} sx={{ p: 1.75 }}>
                    {renderCard(r, (page - 1) * pageSize + i)}
                  </Card>
                ))}
              </AnimatePresence>
            </Stack>
          )}
          {pages > 1 && (
            <Stack alignItems="center" sx={{ mt: 2.5 }}>
              <Pagination count={pages} page={page} onChange={(_, p) => setPage(p)} color="primary" showFirstButton showLastButton siblingCount={wide ? 1 : 0} />
            </Stack>
          )}
        </>
      )}
    </Box>
  );
};

export default ReportPage;
